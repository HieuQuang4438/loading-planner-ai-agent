const svg = (name) => `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${ICONS[name] ?? ''}</svg>`;

// The same icon as an HTML string, for lists built with innerHTML.
export const iconHtml = (name) => `<i class="ic" data-ic="${name}" aria-hidden="true">${svg(name)}</i>`;

// A filled icon element. Decorative (aria-hidden): the button around it has the text or the aria-label.
export function icon(name) {
  const i = el('i', { class: 'ic' });
  i.dataset.ic = name;
  i.setAttribute('aria-hidden', 'true');
  i.innerHTML = svg(name);
  return i;
}

// Fills the empty `<i class="ic" data-ic>` placeholders under `root`.
export function fillIcons(root = document) {
  for (const i of root.querySelectorAll('i.ic[data-ic]:empty')) {
    i.setAttribute('aria-hidden', 'true');
    i.innerHTML = svg(i.dataset.ic);
  }
}

// Every collapsible block (`details > summary`) gets a Lucide chevron on the right; style.css turns it when the block is open.
export function addChevrons(root = document) {
  for (const sum of root.querySelectorAll('details > summary')) {
    if (sum.lastElementChild?.classList.contains('chev')) continue;
    const chev = icon('chevron-down');
    chev.classList.add('chev');
    sum.append(chev);
  }
}

